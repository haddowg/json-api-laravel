<?php

declare(strict_types=1);

/*
 * Drives the byte-compatibility check. It exports the music-catalog documents from this
 * package's testbench workbench and diffs each, normalized, against the Symfony bundle's
 * published copy in `@haddowg/json-api-symfony-specs`, per server. Two document families are
 * covered, each exercising a DISTINCT projector path:
 *
 *   - the OpenAPI document (paths + envelopes + $ref'd components), normalized by
 *     bin/normalize-openapi.php (info + servers[].url sentinels);
 *   - the standalone JSON-Schema document (one object keyed by JSON:API type, each the
 *     type's self-contained resource-object schema with inline permissive
 *     relationships/links/meta), normalized by bin/normalize-json-schema.php (no
 *     sentinels — it carries no platform-specific block).
 *
 * An empty diff = pass; any structural difference fails with a non-zero exit and the diff
 * printed.
 *
 * The Laravel side is (re)generated by the ByteCompat export tests. The bundle side is read
 * from the npm package `package.json` pins (`npm ci` installs it). The package's
 * `versions.json` names the haddowg/json-api version that projected it, and the check fails
 * before diffing unless it is the version installed here: two different cores would make any
 * diff spurious.
 *
 * It also diffs the response documents the two conformance suites share, which the package
 * carries under conformance/.
 *
 * Env:
 *   JSON_API_SYMFONY_SPECS_PATH  a directory holding the bundle documents instead of the
 *                                installed package, e.g. one the bundle's
 *                                `bin/export-specs.php` wrote from unreleased bundle code
 *
 * Usage:  php bin/byte-compat.php
 */

use Composer\InstalledVersions;

$repoRoot = \dirname(__DIR__);
$buildDir = $repoRoot . '/build';
$specsPath = \rtrim(\getenv('JSON_API_SYMFONY_SPECS_PATH') ?: $repoRoot . '/node_modules/@haddowg/json-api-symfony-specs', '/');
// Each server's documents, by the name the package files them under.
$servers = ['default' => 'music-catalog', 'admin' => 'music-catalog-admin'];

function fail(string $message): never
{
    \fwrite(\STDERR, "\n[byte-compat] FAIL: {$message}\n");
    exit(1);
}

function step(string $message): void
{
    \fwrite(\STDOUT, "[byte-compat] {$message}\n");
}

$autoload = $repoRoot . '/vendor/autoload.php';
if (!\is_file($autoload)) {
    fail('this package is not installed; run composer install.');
}
require $autoload;

if (!\is_file("{$specsPath}/versions.json")) {
    fail(
        "the bundle documents are not at {$specsPath}. Run npm ci, which needs a token that can read "
        . 'GitHub Packages (see docs/workbench.md#byte-compatibility), or point JSON_API_SYMFONY_SPECS_PATH '
        . "at a directory the bundle's bin/export-specs.php wrote.",
    );
}

if (!\is_dir($buildDir) && !\mkdir($buildDir, 0o755, true) && !\is_dir($buildDir)) {
    fail("could not create {$buildDir}.");
}

// --- Determinism guard: both documents must come from the same core -------------------
step('checking the bundle documents were projected by the haddowg/json-api installed here');
$specsCore = specsCoreVersion("{$specsPath}/versions.json");
$installedCore = InstalledVersions::getPrettyVersion('haddowg/json-api') ?? 'unknown';
step("  bundle documents: haddowg/json-api {$specsCore}");
step("  this package:     haddowg/json-api {$installedCore}");
if (normalizeVersion($specsCore) !== normalizeVersion($installedCore)) {
    fail(
        "core version skew: the bundle documents were projected by haddowg/json-api {$specsCore}, but {$installedCore} "
        . 'is installed here, so any diff would compare two different projectors. Install the same core '
        . \sprintf("(composer require --no-update 'haddowg/json-api:%s' && composer update haddowg/json-api, ", normalizeVersion($specsCore))
        . 'without committing it, as the byte-compat CI job does), or pin a bundle release projected by the core installed here.',
    );
}
if (isDevVersion($installedCore)) {
    step("  WARNING: {$installedCore} is a development version, which names a branch rather than a commit; the two sides may still differ.");
}

// --- Export the Laravel side (via the ByteCompat testbench exporters) -----------------
step('exporting the Laravel workbench documents (testbench)');
runOrFail(
    [\PHP_BINARY, $repoRoot . '/vendor/bin/phpunit', '--testsuite=ByteCompat'],
    $repoRoot,
    'Laravel export failed',
);
foreach (\array_keys($servers) as $server) {
    foreach (["laravel-{$server}.json", "laravel-schemas-{$server}.json"] as $artifact) {
        if (!\is_file("{$buildDir}/{$artifact}")) {
            fail("Laravel export did not produce build/{$artifact}.");
        }
    }
}

// --- The bundle side (the published documents) -----------------------------------------
foreach ($servers as $name) {
    foreach (["{$name}.openapi.json", "{$name}.schemas.json"] as $document) {
        if (!\is_file("{$specsPath}/{$document}")) {
            fail("the bundle documents in {$specsPath} have no {$document}.");
        }
    }
}

// --- Normalize + diff each document family, per server -------------------------------
$failures = [];
diffFamily('OpenAPI', __DIR__ . '/normalize-openapi.php', $buildDir, $specsPath, '', 'openapi', $servers, $failures);
diffFamily('JSON-Schema', __DIR__ . '/normalize-json-schema.php', $buildDir, $specsPath, 'schemas-', 'schemas', $servers, $failures);

// --- The shared response documents both conformance suites assert against -------------
// Each suite compares its responses to its own copy byte for byte, so the copies must match.
foreach ([['IdentifiedMorphMany', 'tests/Fixtures/IdentifiedMorphMany/documents', 'conformance/identified-morph-many']] as [$label, $laravelDir, $bundleDir]) {
    if (!\is_dir("{$specsPath}/{$bundleDir}")) {
        fail("the bundle documents in {$specsPath} have no {$bundleDir}/.");
    }

    step("diffing the shared {$label} response documents");
    $diff = shellDiff("{$repoRoot}/{$laravelDir}", "{$specsPath}/{$bundleDir}", true);
    if ($diff === '') {
        step("  {$label} documents: EMPTY DIFF — byte-compatible.");
        continue;
    }

    $failures[] = "{$label} documents";
    \fwrite(\STDERR, "\n[byte-compat] {$label} response documents DIFFER (< laravel, > symfony):\n" . $diff . "\n");
}

if ($failures !== []) {
    fail('byte-incompatible document(s): ' . \implode(', ', $failures) . '.');
}

step('OK — every OpenAPI and JSON-Schema document is byte-compatible with the bundle\'s.');
exit(0);

/**
 * The haddowg/json-api version the bundle documents' `versions.json` names.
 */
function specsCoreVersion(string $file): string
{
    try {
        $versions = \json_decode((string) \file_get_contents($file), true, 512, \JSON_THROW_ON_ERROR);
    } catch (\JsonException $exception) {
        fail("{$file} is not valid JSON: {$exception->getMessage()}");
    }

    $core = \is_array($versions) ? ($versions['haddowg/json-api'] ?? null) : null;
    if (!\is_string($core) || $core === '') {
        fail("{$file} names no haddowg/json-api version.");
    }

    return $core;
}

/**
 * A version as Composer reports it, minus a tag's leading `v`, so `v2.1.0` and `2.1.0` agree.
 */
function normalizeVersion(string $version): string
{
    return \preg_replace('/^v(?=\d)/', '', $version) ?? $version;
}

function isDevVersion(string $version): bool
{
    return \str_starts_with($version, 'dev-') || \str_ends_with($version, '-dev');
}

/**
 * @param list<string> $command
 */
function runOrFail(array $command, string $cwd, string $context): void
{
    $descriptors = [0 => \STDIN, 1 => \STDOUT, 2 => \STDERR];
    $process = \proc_open($command, $descriptors, $pipes, $cwd);
    if (!\is_resource($process)) {
        fail("{$context}: could not start " . \implode(' ', $command));
    }

    $code = \proc_close($process);
    if ($code !== 0) {
        fail("{$context} (exit {$code}).");
    }
}

/**
 * Normalizes + diffs one document family (OpenAPI or JSON-Schema) per server: this package's
 * export against the bundle's published document, each through the family's own normalizer.
 * `$infix` is the filename segment of this package's export ('' for OpenAPI's
 * `laravel-<server>.json`, 'schemas-' for `laravel-schemas-<server>.json`); `$kind` is the
 * package's (`<name>.openapi.json`, `<name>.schemas.json`). Any diverging server appends
 * "<label> '<server>'" to $failures and prints its diff; the caller aggregates and fails.
 *
 * @param array<string, string> $servers each server, mapped to the name the package uses
 * @param list<string>         &$failures
 */
function diffFamily(string $label, string $normalizer, string $buildDir, string $specsPath, string $infix, string $kind, array $servers, array &$failures): void
{
    foreach ($servers as $server => $name) {
        step("normalizing + diffing {$label} server '{$server}'");
        $laravelNorm = normalize($normalizer, "{$buildDir}/laravel-{$infix}{$server}.json", "{$buildDir}/n-laravel-{$infix}{$server}.json");
        $symfonyNorm = normalize($normalizer, "{$specsPath}/{$name}.{$kind}.json", "{$buildDir}/n-symfony-{$infix}{$server}.json");

        $diff = shellDiff($laravelNorm, $symfonyNorm);
        if ($diff === '') {
            step("  {$label} server '{$server}': EMPTY DIFF — byte-compatible.");
            continue;
        }

        $failures[] = "{$label} '{$server}'";
        \fwrite(\STDERR, "\n[byte-compat] {$label} server '{$server}' DIFFERS (< laravel, > symfony):\n");
        \fwrite(\STDERR, $diff . "\n");
    }
}

function normalize(string $normalizer, string $input, string $output): string
{
    $result = \shell_exec(\sprintf('%s %s %s', \escapeshellarg(\PHP_BINARY), \escapeshellarg($normalizer), \escapeshellarg($input)));
    if (!\is_string($result)) {
        fail("normalizer produced no output for {$input}.");
    }

    \file_put_contents($output, $result);

    return $output;
}

/**
 * A unified diff of two files, distinguishing "identical" from "the diff tool failed" (which
 * `shell_exec` cannot — it returns null for both an empty diff and a spawn error, so a runner
 * without diffutils would silently green-light real drift). Runs `diff` via {@see \proc_open}
 * and keys on its exit code: `0` = identical (empty string), `1` = differ (the diff text),
 * anything else (or a spawn failure) is a hard {@see fail()}.
 */
function shellDiff(string $a, string $b, bool $recursive = false): string
{
    $descriptors = [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w']];
    $process = \proc_open($recursive ? ['diff', '-ru', $a, $b] : ['diff', '-u', $a, $b], $descriptors, $pipes);
    if (!\is_resource($process)) {
        fail('could not start diff.');
    }

    \fclose($pipes[0]);
    $stdout = \stream_get_contents($pipes[1]);
    $stderr = \stream_get_contents($pipes[2]);
    \fclose($pipes[1]);
    \fclose($pipes[2]);
    $code = \proc_close($process);

    if ($code === 0) {
        return '';
    }
    if ($code === 1) {
        return \trim(\is_string($stdout) ? $stdout : '');
    }

    fail(\sprintf('diff failed (exit %d): %s', $code, \trim(\is_string($stderr) ? $stderr : '')));
}
