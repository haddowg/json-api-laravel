<?php

declare(strict_types=1);

/*
 * Drives the byte-compatibility check (PLAN decision 11): it exports the music-catalog
 * documents from BOTH this package's testbench workbench and the sibling Symfony bundle's
 * example app, normalizes each, and diffs them per server. Two document families are
 * covered, each exercising a DISTINCT projector path:
 *
 *   - the OpenAPI document (paths + envelopes + $ref'd components), normalized by
 *     bin/normalize-openapi.php (info + servers[].url sentinels);
 *   - the standalone JSON-Schema document (one object keyed by JSON:API type, each the
 *     type's self-contained resource-object schema with inline permissive
 *     relationships/links/meta), normalized by bin/normalize-json-schema.php (no
 *     sentinels — it carries no platform-specific block).
 *
 * An empty diff = pass; any structural difference fails with a non-zero exit and the diff
 * printed.
 *
 * The Laravel side is (re)generated by the ByteCompat export tests; the Symfony side is
 * produced by booting the bundle's MusicCatalogKernel and running its
 * `json-api:openapi:export` + `json-api:json-schema:export` commands. Both trees must
 * resolve the SAME core commit for the diff to be meaningful — locally both symlink the
 * sibling core; in CI both install core from the same VCS ref. The script asserts the two
 * resolved core references match and fails early (a spurious diff) if they differ.
 *
 * Env:
 *   JSON_API_SYMFONY_PATH  path to the sibling bundle checkout (default ../json-api-symfony)
 *
 * Usage:  php bin/byte-compat.php
 */

$repoRoot = \dirname(__DIR__);
$buildDir = $repoRoot . '/build';
$bundlePath = \rtrim(\getenv('JSON_API_SYMFONY_PATH') ?: $repoRoot . '/../json-api-symfony', '/');
$servers = ['default', 'admin'];

function fail(string $message): never
{
    \fwrite(\STDERR, "\n[byte-compat] FAIL: {$message}\n");
    exit(1);
}

function step(string $message): void
{
    \fwrite(\STDOUT, "[byte-compat] {$message}\n");
}

if (!\is_dir($bundlePath)) {
    fail("bundle checkout not found at {$bundlePath} (set JSON_API_SYMFONY_PATH).");
}
$bundleAutoload = $bundlePath . '/vendor/autoload.php';
if (!\is_file($bundleAutoload)) {
    fail("bundle is not installed ({$bundleAutoload} missing); run composer install in {$bundlePath}.");
}

if (!\is_dir($buildDir) && !\mkdir($buildDir, 0o755, true) && !\is_dir($buildDir)) {
    fail("could not create {$buildDir}.");
}

// --- Determinism guard: both trees must resolve the same core commit -----------------
step('checking both trees resolve the same haddowg/json-api core ref');
$laravelCoreRef = coreReference($repoRoot);
$bundleCoreRef = coreReference($bundlePath);
step("  laravel core: {$laravelCoreRef}");
step("  bundle  core: {$bundleCoreRef}");
if ($laravelCoreRef !== $bundleCoreRef) {
    fail("core version skew — the two apps resolve different haddowg/json-api commits, so any diff would be spurious. Reinstall so both resolve the same ref.");
}

// --- Export the Laravel side (via the ByteCompat testbench exporters) -----------------
step('exporting the Laravel workbench documents (testbench)');
runOrFail(
    [\PHP_BINARY, $repoRoot . '/vendor/bin/phpunit', '--testsuite=ByteCompat'],
    $repoRoot,
    'Laravel export failed',
);
foreach ($servers as $server) {
    foreach (["laravel-{$server}.json", "laravel-schemas-{$server}.json"] as $artifact) {
        if (!\is_file("{$buildDir}/{$artifact}")) {
            fail("Laravel export did not produce build/{$artifact}.");
        }
    }
}

// --- Export the Symfony side (boot the bundle example kernel) -------------------------
step('exporting the Symfony bundle documents (MusicCatalogKernel)');
runOrFail(
    [\PHP_BINARY, __DIR__ . '/export-symfony-documents.php', $buildDir],
    $repoRoot,
    'Symfony export failed',
    ['JSON_API_SYMFONY_PATH' => $bundlePath],
);
foreach ($servers as $server) {
    foreach (["symfony-{$server}.json", "symfony-schemas-{$server}.json"] as $artifact) {
        if (!\is_file("{$buildDir}/{$artifact}")) {
            fail("Symfony export did not produce build/{$artifact}.");
        }
    }
}

// --- Normalize + diff each document family, per server -------------------------------
$failures = [];
diffFamily('OpenAPI', __DIR__ . '/normalize-openapi.php', $buildDir, '', $servers, $failures);
diffFamily('JSON-Schema', __DIR__ . '/normalize-json-schema.php', $buildDir, 'schemas-', $servers, $failures);

if ($failures !== []) {
    fail('byte-incompatible document(s): ' . \implode(', ', $failures) . '.');
}

step('OK — every OpenAPI and JSON-Schema document is byte-compatible with the bundle.');
exit(0);

/**
 * A stable identity for the haddowg/json-api core a tree resolves, used to guard against a
 * spurious diff from core skew.
 *
 * In LOCAL dev both trees symlink the SAME sibling checkout via a global path repository —
 * the installed.json records the commit at *install time* (which drifts between the two
 * trees) even though the live symlink target is identical, so a metadata compare would
 * false-positive. When the vendored core is a symlink we therefore key on its realpath (the
 * live code both trees share). In CI both trees install core from the same VCS ref (a real
 * dist install, not a symlink), so we key on the installed.json reference and a genuine skew
 * still fails the guard.
 */
function coreReference(string $treeRoot): string
{
    $vendorCore = $treeRoot . '/vendor/haddowg/json-api';
    if (\is_link($vendorCore)) {
        $target = \realpath($vendorCore);
        if ($target !== false) {
            return 'path:' . $target;
        }
    }

    $installed = $treeRoot . '/vendor/composer/installed.json';
    if (!\is_file($installed)) {
        fail("no vendor/composer/installed.json in {$treeRoot}; run composer install.");
    }

    /** @var array{packages?: list<array<string, mixed>>} $data */
    $data = \json_decode((string) \file_get_contents($installed), true, 512, \JSON_THROW_ON_ERROR);
    foreach ($data['packages'] ?? [] as $package) {
        if (($package['name'] ?? null) === 'haddowg/json-api') {
            $source = \is_array($package['source'] ?? null) ? $package['source'] : [];
            $reference = \is_string($source['reference'] ?? null) ? $source['reference'] : '';
            $dist = \is_array($package['dist'] ?? null) ? $package['dist'] : [];
            $distReference = \is_string($dist['reference'] ?? null) ? $dist['reference'] : '';

            return $reference !== '' ? $reference : ($distReference !== '' ? $distReference : 'unknown');
        }
    }

    fail("haddowg/json-api not found in {$treeRoot}/vendor/composer/installed.json.");
}

/**
 * @param list<string>          $command
 * @param array<string, string> $env
 */
function runOrFail(array $command, string $cwd, string $context, array $env = []): void
{
    $descriptors = [0 => \STDIN, 1 => \STDOUT, 2 => \STDERR];
    $process = \proc_open($command, $descriptors, $pipes, $cwd, $env === [] ? null : \array_merge(\getenv() ?: [], $env));
    if (!\is_resource($process)) {
        fail("{$context}: could not start " . \implode(' ', $command));
    }

    $code = \proc_close($process);
    if ($code !== 0) {
        fail("{$context} (exit {$code}).");
    }
}

/**
 * Normalizes + diffs one document family (OpenAPI or JSON-Schema) across both frameworks,
 * per server, using the family's own normalizer. `$infix` is the filename segment between
 * the framework prefix and the server ('' for OpenAPI's `laravel-<server>.json`,
 * 'schemas-' for `laravel-schemas-<server>.json`). Any diverging server appends
 * "<label> '<server>'" to $failures and prints its diff; the caller aggregates and fails.
 *
 * @param list<string>  $servers
 * @param list<string> &$failures
 */
function diffFamily(string $label, string $normalizer, string $buildDir, string $infix, array $servers, array &$failures): void
{
    foreach ($servers as $server) {
        step("normalizing + diffing {$label} server '{$server}'");
        $laravelNorm = normalize($normalizer, "{$buildDir}/laravel-{$infix}{$server}.json", "{$buildDir}/n-laravel-{$infix}{$server}.json");
        $symfonyNorm = normalize($normalizer, "{$buildDir}/symfony-{$infix}{$server}.json", "{$buildDir}/n-symfony-{$infix}{$server}.json");

        $diff = shellDiff($laravelNorm, $symfonyNorm);
        if ($diff === '') {
            step("  {$label} server '{$server}': EMPTY DIFF — byte-compatible.");
            continue;
        }

        $failures[] = "{$label} '{$server}'";
        \fwrite(\STDERR, "\n[byte-compat] {$label} server '{$server}' DIFFERS (< laravel, > symfony):\n");
        \fwrite(\STDERR, $diff . "\n");
    }
}

function normalize(string $normalizer, string $input, string $output): string
{
    $result = \shell_exec(\sprintf('%s %s %s', \escapeshellarg(\PHP_BINARY), \escapeshellarg($normalizer), \escapeshellarg($input)));
    if (!\is_string($result)) {
        fail("normalizer produced no output for {$input}.");
    }

    \file_put_contents($output, $result);

    return $output;
}

/**
 * A unified diff of two files, distinguishing "identical" from "the diff tool failed" (which
 * `shell_exec` cannot — it returns null for both an empty diff and a spawn error, so a runner
 * without diffutils would silently green-light real drift). Runs `diff` via {@see \proc_open}
 * and keys on its exit code: `0` = identical (empty string), `1` = differ (the diff text),
 * anything else (or a spawn failure) is a hard {@see fail()}.
 */
function shellDiff(string $a, string $b): string
{
    $descriptors = [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w']];
    $process = \proc_open(['diff', '-u', $a, $b], $descriptors, $pipes);
    if (!\is_resource($process)) {
        fail('could not start diff.');
    }

    \fclose($pipes[0]);
    $stdout = \stream_get_contents($pipes[1]);
    $stderr = \stream_get_contents($pipes[2]);
    \fclose($pipes[1]);
    \fclose($pipes[2]);
    $code = \proc_close($process);

    if ($code === 0) {
        return '';
    }
    if ($code === 1) {
        return \trim(\is_string($stdout) ? $stdout : '');
    }

    fail(\sprintf('diff failed (exit %d): %s', $code, \trim(\is_string($stderr) ? $stderr : '')));
}
